import { useState } from 'react';
import { Clapperboard, Clock, ExternalLink, Film, Loader2, QrCode, RotateCw } from 'lucide-react';
import { Modal, Badge, SafeQRCode } from './ui';
import { toMediaUrl } from '../lib/mediaUrl';
import { createRecordingSession } from '../api';

const ROLE_LABELS = {
  hook: { label: 'Hook', variant: 'rose' },
  feature: { label: 'Feature', variant: 'cyan' },
  cta: { label: 'CTA', variant: 'emerald' },
};

function formatSeconds(sec) {
  const s = Number(sec) || 0;
  return `${s.toFixed(1)}s`;
}

// Mirrors ExportGallery.jsx's buildQuickPostUrl for the guided-take filming
// flow -- see App.jsx's `filmingSessionId` handling and
// scripts/api_recording.py (Phase B/C of
// C:\Users\Winon\.claude\plans\cheeky-cooking-quokka.md).
function buildFilmingUrl(mobileBaseUrl, sessionId) {
  const params = new URLSearchParams({ film: '1', session: sessionId });
  return `${mobileBaseUrl}/?${params.toString()}`;
}

// Displays a shot-list generated by scripts/shot_list_builder.py: one row
// per script beat with its exact TTS timing (not an estimate) and a fixed-
// camera-angle filming direction.
export default function ShotListModal({
  isOpen, onClose, productId, mobileBaseUrl, result, onRegenerate, regenerating = false,
}) {
  const [creatingSession, setCreatingSession] = useState(false);
  const [filmingUrl, setFilmingUrl] = useState(null);
  const [sessionError, setSessionError] = useState(null);

  if (!result) return null;
  const { angle, shot_list: shotList = [], voice_audio_path: voiceAudioPath, total_duration: totalDuration } = result;

  const handleStartSession = async () => {
    if (!productId || !angle?.angle_id) return;
    setCreatingSession(true);
    setSessionError(null);
    try {
      const res = await createRecordingSession(productId, angle.angle_id);
      setFilmingUrl(buildFilmingUrl(mobileBaseUrl, res.session_id));
    } catch (err) {
      setSessionError(err.friendlyMessage || err.message || 'สร้างเซสชันถ่ายทำไม่สำเร็จ');
    } finally {
      setCreatingSession(false);
    }
  };

  const handleClose = () => {
    setFilmingUrl(null);
    setSessionError(null);
    onClose?.();
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={handleClose}
      title={`แผนถ่าย: ${angle?.angle_name || ''}`}
      subtitle={`${shotList.length} ช็อต · ยาวรวม ${formatSeconds(totalDuration)} (จากจังหวะเสียงพากย์จริง)`}
      maxWidth="max-w-3xl"
    >
      <div className="space-y-4">
        {onRegenerate && (
          <div className="flex justify-end -mt-1 -mb-1">
            <button
              type="button"
              onClick={onRegenerate}
              disabled={regenerating}
              title="สังเคราะห์เสียงพากย์และคำนวณจังหวะ beat ใหม่ทั้งหมด"
              className="text-[11px] text-slate-500 hover:text-slate-300 flex items-center gap-1 cursor-pointer disabled:opacity-50 disabled:cursor-wait transition-colors"
            >
              {regenerating ? <Loader2 className="w-3 h-3 animate-spin" /> : <RotateCw className="w-3 h-3" />}
              สร้างแผนถ่ายใหม่
            </button>
          </div>
        )}

        {voiceAudioPath && (
          <div className="p-3 rounded-xl bg-white/[0.05] border border-white/[0.08] space-y-1.5">
            <span className="text-[11px] font-bold text-slate-400 uppercase tracking-wider flex items-center gap-1.5">
              <Clock className="w-3.5 h-3.5" /> เสียงนำถ่าย (guide track) — เปิดฟังคลอตอนถ่ายได้เลย
            </span>
            <audio controls className="w-full h-9" src={toMediaUrl(voiceAudioPath)} />
          </div>
        )}

        <div className="p-3 rounded-xl bg-amber-500/10 border border-amber-500/25 text-xs text-amber-200 leading-relaxed">
          ตั้งกล้อง/มือถือมุมเดียวแล้ว<span className="font-bold">ห้ามขยับตลอดทั้งเทกหลัก</span> —
          ทำแอคชั่นตามคำแนะนำแต่ละช็อตให้ตรงจังหวะเสียง ส่วนความหลากหลายของภาพ (ซูม/เน้นจังหวะ)
          ระบบจะใส่ให้อัตโนมัติตอนตัดต่อ
        </div>

        <div className="space-y-2 max-h-[50vh] overflow-y-auto pr-1">
          {shotList.map((beat) => {
            const roleMeta = ROLE_LABELS[beat.role] || { label: beat.role, variant: 'slate' };
            return (
              <div
                key={beat.beat_index}
                className="p-3 rounded-xl bg-[#0B0F19] border border-white/[0.08] space-y-1.5"
              >
                <div className="flex items-center justify-between gap-2">
                  <div className="flex items-center gap-2">
                    <span className="text-[11px] font-mono text-slate-500">#{beat.beat_index + 1}</span>
                    <Badge variant={roleMeta.variant} size="sm">{roleMeta.label}</Badge>
                    {beat.is_separate_clip && (
                      <Badge variant="purple" size="sm" icon={Film}>แยกคลิป</Badge>
                    )}
                  </div>
                  <span className="text-[11px] font-mono text-slate-400">
                    {formatSeconds(beat.start)} – {formatSeconds(beat.end)} ({formatSeconds(beat.planned_duration)})
                  </span>
                </div>
                <p className="text-xs text-slate-300 font-kanit leading-snug">{beat.text}</p>
                <p className="text-xs text-amber-200/90 flex items-start gap-1.5">
                  <Clapperboard className="w-3.5 h-3.5 flex-shrink-0 mt-0.5" />
                  <span>{beat.camera_direction}</span>
                </p>
              </div>
            );
          })}
        </div>

        <div className="pt-3 border-t border-white/[0.08] space-y-3">
          {filmingUrl ? (
            <div className="flex flex-col items-center gap-2 p-4 rounded-xl bg-white/[0.05] border border-white/[0.08]">
              <div className="p-2 bg-white rounded-xl shadow-lg">
                <SafeQRCode value={filmingUrl} size={150} level="M" />
              </div>
              <p className="text-[11px] text-slate-400 text-center">
                สแกนด้วยมือถือ (ต้องอยู่ Wi-Fi วงเดียวกับคอมพิวเตอร์เครื่องนี้) เพื่อเปิดหน้าถ่ายทำพร้อมไกด์ทีละช็อต
              </p>
              <button
                type="button"
                onClick={() => window.open(filmingUrl, '_blank', 'noopener')}
                className="text-xs text-cyan-300 hover:text-cyan-200 flex items-center gap-1.5 font-bold cursor-pointer"
              >
                <ExternalLink className="w-3.5 h-3.5" />
                หรือเปิดหน้ากล้องบนเครื่องนี้เลย (ไม่ต้องสแกน)
              </button>
            </div>
          ) : (
            <div className="flex items-center justify-between gap-2">
              <span className="text-[11px] text-slate-500">
                สแกน QR เพื่อถ่ายในแอปพร้อมไกด์ทีละช็อต ตรงตามแผนด้านบน
              </span>
              <button
                type="button"
                onClick={handleStartSession}
                disabled={creatingSession}
                className="px-3 py-1.5 rounded-xl bg-amber-500/15 hover:bg-amber-500/25 border border-amber-500/30 text-amber-300 text-xs font-bold flex items-center gap-1.5 cursor-pointer disabled:opacity-50 disabled:cursor-wait transition-all"
              >
                {creatingSession ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <QrCode className="w-3.5 h-3.5" />}
                เริ่มเซสชันถ่ายทำ (QR)
              </button>
            </div>
          )}
          {sessionError && (
            <p className="text-[11px] text-rose-400">{sessionError}</p>
          )}
        </div>
      </div>
    </Modal>
  );
}
