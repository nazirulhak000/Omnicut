export function getProductCategoryType(productObj) {
  if (!productObj) return 'generic';

  const code = (productObj.product_code || productObj.id || productObj.code || '').toLowerCase();
  const name = (productObj.name || productObj.title || productObj.product_name || '').toLowerCase();
  const cat = (productObj.category || '').toLowerCase();
  const combined = `${code} ${name} ${cat}`;

  if (
    combined.includes('ear') ||
    combined.includes('jbl') ||
    combined.includes('headphone') ||
    combined.includes('earphone') ||
    combined.includes('หูฟัง') ||
    combined.includes('audio') ||
    combined.includes('sound') ||
    combined.includes('synmax')
  ) {
    return 'audio';
  }

  if (
    combined.includes('hat') ||
    combined.includes('fan') ||
    combined.includes('พัดลม') ||
    combined.includes('cool') ||
    combined.includes('hoy') ||
    combined.includes('blu01') ||
    combined.includes('ora01')
  ) {
    return 'cooling';
  }

  if (
    combined.includes('ess') ||
    combined.includes('char') ||
    combined.includes('ชาร์จ') ||
    combined.includes('ปลั๊ก') ||
    combined.includes('power') ||
    combined.includes('gan') ||
    combined.includes('tos') ||
    combined.includes('battery')
  ) {
    return 'power';
  }

  if (
    combined.includes('mic') ||
    combined.includes('goc') ||
    combined.includes('ไมค์') ||
    combined.includes('ไมโครโฟน')
  ) {
    return 'microphone';
  }

  if (
    combined.includes('mouse') ||
    combined.includes('เมาส์') ||
    combined.includes('keyboard') ||
    combined.includes('คีย์บอร์ด') ||
    combined.includes('log') ||
    combined.includes('mon') ||
    combined.includes('iwa')
  ) {
    return 'desk_setup';
  }

  return 'generic';
}

export function getCategoryDisplayName(categoryType) {
  switch (categoryType) {
    case 'audio':
      return 'หูฟัง / เครื่องเสียง';
    case 'cooling':
      return 'พัดลม / ความเย็น';
    case 'power':
      return 'หัวชาร์จ / แบตเตอรี่ / ปลั๊กไฟ';
    case 'microphone':
      return 'ไมโครโฟน / สตรีมมิ่ง';
    case 'desk_setup':
      return 'อุปกรณ์โต๊ะทำงาน / เมาส์ / คีย์บอร์ด';
    default:
      return 'แกดเจ็ตและสินค้าทั่วไป';
  }
}

function cleanText(text) {
  if (!text) return '';
  return text.replace(/[!?,.":;“”]/g, ' ').replace(/\s+/g, ' ').trim();
}

export function convertAngleToPOVDialogue(angle, productName) {
  const pName = productName || 'สินค้าตัวนี้';
  const pain = cleanText(angle?.pain_point) || 'เจอปัญหาของเดิมไม่ตอบโจทย์ หงุดหงิดมากกก';
  const feat = cleanText(angle?.key_features);
  const featureText = feat ? feat.slice(0, 42) : 'ตัวนี้ฟังก์ชันครบ คุณภาพแน่น คุ้มค่ามาก';
  const price = cleanText(angle?.price_deal);
  const dealText = price ? ` มีดีลพิเศษ ${price}` : '';

  return `แฟน: "เธอออ ${pain} ช่วยด้วยยย 😱"
ฉัน: "ใจเย็น! ในกระเป๋ามี ${pName} ตัวเด็ด หยิบมาใช้เลย"
แฟน: "มันจะช่วยแก้ปัญหาได้จริงเหรอเธอ"
ฉัน: "${featureText}${dealText} ลองแล้วชีวิตดีขึ้นแน่นอน"
แฟน: "เห้ยยย จริงด้วย รอดตายแล้ว ขอบคุณน้าาา 🥰"`;
}

