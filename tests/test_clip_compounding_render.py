"""
Regression test for transition overlap compounding bug.
Verifies that rendering multiple consecutive times does NOT inflate
clip durations or trim_ends repeatedly.
"""

from unittest.mock import patch, MagicMock
from pathlib import Path

from scripts.pipeline_context import PipelineContext
from scripts.stages.shot_matching_stage import ShotMatchingStage
from scripts.stages.video_assembly_stage import VideoAssemblyStage
from scripts.video_editor import VideoEditor


def test_video_assembly_does_not_compound_clip_durations_on_consecutive_runs():
    """
    Test that re-rendering an existing project or calling VideoAssemblyStage
    multiple times with existing clip_list does NOT continuously add overlap.
    """
    initial_clips = [
        {"id": "clip_0", "duration": 2.5, "trim_start": 0.0, "trim_end": 2.5},
        {"id": "clip_1", "duration": 3.0, "trim_start": 10.0, "trim_end": 13.0},
        {"id": "clip_2", "duration": 2.0, "trim_start": 5.0, "trim_end": 7.0},
    ]
    transitions = [
        {"type": "fade", "duration": 0.25},
        {"type": "dissolve", "duration": 0.25},
    ]

    # Run 1: Existing clips passed in (e.g. from editor)
    ctx1 = PipelineContext(
        product_name="TestProduct",
        raw_video_path="dummy.mp4",
        clip_list=[dict(c) for c in initial_clips],
        transitions=transitions,
        export_mp4=False,
    )
    # Simulate shot matching with existing clips
    ShotMatchingStage.run(ctx1)
    assert ctx1.is_newly_generated_clips is False
    assert ctx1.actual_clip_list == initial_clips

    # Simulate assembly
    with patch("scripts.project_manifest.ProjectManifest.save") as mock_save:
        VideoAssemblyStage.run(ctx1)

    # Durations should remain untouched because clips were not newly generated
    for orig, updated in zip(initial_clips, ctx1.actual_clip_list):
        assert updated["duration"] == orig["duration"], f"Clip {updated['id']} duration inflated!"
        assert updated["trim_end"] == orig["trim_end"], f"Clip {updated['id']} trim_end inflated!"

    # Run 2: Re-rendering with the saved clips
    ctx2 = PipelineContext(
        product_name="TestProduct",
        raw_video_path="dummy.mp4",
        clip_list=ctx1.actual_clip_list,
        transitions=transitions,
        export_mp4=False,
    )
    ShotMatchingStage.run(ctx2)
    assert ctx2.is_newly_generated_clips is False

    with patch("scripts.project_manifest.ProjectManifest.save") as mock_save:
        VideoAssemblyStage.run(ctx2)

    # Durations must STILL be identical to initial_clips
    for orig, updated in zip(initial_clips, ctx2.actual_clip_list):
        assert updated["duration"] == orig["duration"]
        assert updated["trim_end"] == orig["trim_end"]


def test_fresh_clips_receive_overlap_compensation_only_once():
    """
    Test that fresh clips generated by ShotMatchingStage receive overlap
    compensation exactly once during initial assembly.
    """
    ctx = PipelineContext(
        product_name="TestProduct",
        raw_video_path="dummy.mp4",
        clip_list=None,  # No clips provided -> fresh generation
        transitions=[{"type": "fade", "duration": 0.25}],
        total_duration=5.0,
        export_mp4=False,
    )
    ctx.is_newly_generated_clips = True
    ctx.actual_clip_list = [
        {"id": "clip_0", "duration": 2.5, "trim_start": 0.0, "trim_end": 2.5},
        {"id": "clip_1", "duration": 2.5, "trim_start": 2.5, "trim_end": 5.0},
    ]

    with patch("scripts.project_manifest.ProjectManifest.save") as mock_save:
        VideoAssemblyStage.run(ctx)

    # First clip got +0.25 overlap compensation
    assert ctx.actual_clip_list[0]["duration"] == 2.75
    assert ctx.actual_clip_list[0]["trim_end"] == 2.75
    assert ctx.actual_clip_list[0].get("_overlap_compensated") is True

    # Last clip should NOT get overlap compensation
    assert ctx.actual_clip_list[1]["duration"] == 2.5
    assert ctx.actual_clip_list[1]["trim_end"] == 5.0

    # If VideoAssemblyStage runs again on the same clips, it must not inflate again
    with patch("scripts.project_manifest.ProjectManifest.save") as mock_save:
        VideoAssemblyStage.run(ctx)

    assert ctx.actual_clip_list[0]["duration"] == 2.75
    assert ctx.actual_clip_list[0]["trim_end"] == 2.75
