"""
Flow MCP Client for OmniCut Pro Studio.
Connects to the local flow-mcp service (running on port 8787 by default)
driving Google Flow (flow.google.com) over Chrome DevTools Protocol.
"""

from __future__ import annotations

import json
import logging
import os
import subprocess
import time
from pathlib import Path
from typing import Any, Dict, List, Optional
import urllib.request
import urllib.error

logger = logging.getLogger("omnicut.flow_client")

FLOW_MCP_PORT = int(os.environ.get("FLOW_MCP_PORT", 8787))
FLOW_MCP_HOST = f"http://127.0.0.1:{FLOW_MCP_PORT}"
FLOW_MCP_HOME = Path(os.environ.get("FLOW_MCP_HOME", Path.home() / ".flow-mcp"))
TOKEN_FILE = FLOW_MCP_HOME / "token"
REPO_ROOT = Path(__file__).resolve().parent.parent
FLOW_MCP_DIR = REPO_ROOT / "tools" / "flow-mcp"


class FlowClientError(Exception):
    """Raised when communication with flow-mcp service fails."""
    pass


class FlowClient:
    def __init__(self, host: str = FLOW_MCP_HOST, token_file: Path = TOKEN_FILE):
        self.host = host.rstrip("/")
        self.token_file = token_file

    def get_token(self) -> str:
        """Reads authentication token generated by flow-mcp."""
        if self.token_file.exists():
            try:
                return self.token_file.read_text(encoding="utf-8").strip()
            except Exception as e:
                logger.warning(f"Failed to read token file {self.token_file}: {e}")
        return ""

    def is_healthy(self, timeout: float = 2.0) -> bool:
        """Checks if flow-mcp HTTP service is alive."""
        url = f"{self.host}/api/health"
        req = urllib.request.Request(url, headers={"User-Agent": "OmniCut-FlowClient"})
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                if resp.status == 200:
                    data = json.loads(resp.read().decode("utf-8"))
                    return data.get("name") == "flow-mcp"
        except Exception:
            return False
        return False

    def _post(self, endpoint: str, payload: Optional[Dict[str, Any]] = None, timeout: float = 45.0) -> Dict[str, Any]:
        """Makes an authenticated POST request to flow-mcp."""
        token = self.get_token()
        headers = {
            "Content-Type": "application/json",
            "User-Agent": "OmniCut-FlowClient",
        }
        if token:
            headers["x-flow-token"] = token

        body = json.dumps(payload or {}).encode("utf-8")
        url = f"{self.host}/api/{endpoint.lstrip('/')}"
        req = urllib.request.Request(url, data=body, headers=headers, method="POST")

        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                res_data = resp.read().decode("utf-8")
                return json.loads(res_data) if res_data else {}
        except urllib.error.HTTPError as e:
            err_msg = e.read().decode("utf-8")
            logger.error(f"flow-mcp error [{e.code}] {url}: {err_msg}")
            try:
                err_json = json.loads(err_msg)
                raise FlowClientError(err_json.get("error", err_msg))
            except json.JSONDecodeError:
                raise FlowClientError(f"HTTP {e.code}: {err_msg}")
        except urllib.error.URLError as e:
            logger.error(f"Cannot connect to flow-mcp service at {self.host}: {e.reason}")
            raise FlowClientError(f"Cannot connect to flow-mcp at {self.host}: {e.reason}")

    def get_status(self, detailed: bool = False) -> Dict[str, Any]:
        """Gets current Google Flow state (signed in, project open, credits)."""
        return self._post("status", {"detailed": detailed})

    def generate(self, project: str, scenes: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Queues generation of scenes in Google Flow.
        Each scene dict:
          - prompt: str
          - type: 'video' | 'image'
          - aspect_ratio: '9:16' | '16:9'
          - reference_images: list of absolute file paths or asset:<name>
          - first_frame: absolute file path
          - max_credits: int (safety cap)
        """
        return self._post("generate", {"project": project, "scenes": scenes})

    def wait(self, job_ids: Optional[List[str]] = None, timeout_seconds: int = 40) -> Dict[str, Any]:
        """Waits for queued generation jobs or task_id."""
        payload: Dict[str, Any] = {"timeout_seconds": timeout_seconds}
        if job_ids:
            payload["job_ids"] = job_ids
        return self._post("wait", payload, timeout=float(timeout_seconds + 5))

    def cancel(self, job_id: str) -> Dict[str, Any]:
        """Cancels a queued job."""
        return self._post("cancel", {"job_id": job_id})

    def retry(self, job_ids: Optional[List[str]] = None) -> Dict[str, Any]:
        """Retries failed generation jobs."""
        payload: Dict[str, Any] = {}
        if job_ids:
            payload["job_ids"] = job_ids
        return self._post("retry", payload)

    def list_assets(self, kind: Optional[str] = None) -> Dict[str, Any]:
        """Lists images and videos in currently open Flow project."""
        payload = {"kind": kind} if kind else {}
        return self._post("assets", payload)

    def download(self, title_prefix: str, upscale: bool = False) -> Dict[str, Any]:
        """Downloads finished asset from project matching title prefix."""
        return self._post("download", {"title": title_prefix, "upscale": upscale})

    def upload_file(self, file_path: str, custom_name: Optional[str] = None) -> str:
        """Uploads a local reference image to flow-mcp upload directory."""
        path = Path(file_path)
        if not path.is_file():
            raise FileNotFoundError(f"File not found: {file_path}")

        name = custom_name or path.name
        url = f"{self.host}/api/upload?name={urllib.parse.quote(name)}"
        token = self.get_token()
        headers = {
            "Content-Type": "application/octet-stream",
            "User-Agent": "OmniCut-FlowClient",
        }
        if token:
            headers["x-flow-token"] = token

        data = path.read_bytes()
        req = urllib.request.Request(url, data=data, headers=headers, method="POST")

        try:
            with urllib.request.urlopen(req, timeout=30.0) as resp:
                res = json.loads(resp.read().decode("utf-8"))
                return res.get("path", "")
        except Exception as e:
            raise FlowClientError(f"Failed to upload reference {file_path}: {e}")

    @staticmethod
    def start_service_daemon() -> subprocess.Popen:
        """Starts the flow-mcp service in background if not running."""
        node_bin = "node"
        entrypoint = FLOW_MCP_DIR / "dist" / "studio.js"
        if not entrypoint.exists():
            raise FileNotFoundError(f"flow-mcp not built. Missing {entrypoint}")

        proc = subprocess.Popen(
            [node_bin, str(entrypoint)],
            cwd=str(FLOW_MCP_DIR),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0,
        )
        # Give it a brief moment to boot
        time.sleep(1.5)
        return proc


_default_client: Optional[FlowClient] = None

def get_flow_client() -> FlowClient:
    global _default_client
    if _default_client is None:
        _default_client = FlowClient()
    return _default_client
