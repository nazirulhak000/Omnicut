"""Derive the HyperFrames kit channel config from the channel registry.

``_Docs/channels.json`` (via ``scripts.channel_store``) is the single source
of truth; ``03_Projects/_HyperFrames_Studio/kit/channels.js`` is a derived
file consumed by ``HF.applyChannel()`` in ``kit/kit.js``::

    window.HF_CHANNELS = { <id>: {name, handle, avatar, watermark, followTitle}, ... };

``avatar`` is relative to the studio root (the kit's parent folder), so a
channel avatar must live inside ``_HyperFrames_Studio``.

Usage::

    python tools/sync_channels.py            # dry-run: print unified diff, write nothing
    python tools/sync_channels.py --apply    # validate, keep channels.js.bak, write atomically

Exit codes: 0 ok (dry-run or applied, including "no changes"), 2 error
(kit folder missing, invalid registry, avatar outside the studio root).
Every channel (draft/active/archived) is emitted so existing compositions
that reference a channel keep resolving; readiness gaps are printed as
warnings.  The registry is only read, never written.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path, PurePosixPath
from typing import Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from scripts import config  # noqa: E402
from scripts.channel_store import ChannelError, ChannelStore, readiness  # noqa: E402

JS_IDENTIFIER_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
KIT_KEYS = ("name", "handle", "avatar", "watermark", "followTitle")
HEADER = (
    "// GENERATED by tools/sync_channels.py from _Docs/channels.json -- do not edit by hand.\n"
    "// Edit channels in the OmniCut channel registry (/api/channels), then run:\n"
    "//   python tools/sync_channels.py --apply\n"
    '// One entry per TikTok channel. A clip picks its channel with data-channel="<id>" on #root (default "main").\n'
    "// HF.applyChannel() (kit/kit.js) writes these into the watermark (#wm) and the follow outro (#fl-*).\n"
    "// Make clips with: python kit/new_clip.py <clip-id> --product <code> --vo <wav> --channel <id>\n"
)


class SyncError(Exception):
    pass


def _js_string(value: str) -> str:
    # JSON string literals are valid JS string literals (quotes, backslashes and
    # control chars escaped); registry validation already rejects U+2028/2029.
    return json.dumps(value, ensure_ascii=False)


def _js_key(channel_id: str) -> str:
    return channel_id if JS_IDENTIFIER_RE.match(channel_id) else _js_string(channel_id)


def kit_avatar_path(avatar_rel: str, *, project_root: Path, studio_root: Path) -> str:
    """Project-root-relative avatar -> studio-root-relative POSIX path for the kit."""
    if not avatar_rel:
        return ""
    absolute = (project_root.resolve() / Path(*PurePosixPath(avatar_rel).parts)).resolve()
    studio = studio_root.resolve()
    if studio not in absolute.parents:
        raise SyncError(
            f"รูปโปรไฟล์ {avatar_rel} อยู่นอกโฟลเดอร์ HyperFrames Studio ({studio}) "
            "จึงใช้ใน kit ไม่ได้ กรุณาย้ายรูปไปไว้ใน assets/ ของ Studio แล้วแก้ที่อยู่ในทะเบียนช่อง"
        )
    return absolute.relative_to(studio).as_posix()


def build_kit_entries(channels: list[dict], *, project_root: Path, studio_root: Path) -> list[tuple[str, str, dict]]:
    entries = []
    for channel in channels:
        for source_field in ("display_name", "handle", "watermark_text", "follow_title", "avatar_asset_path"):
            value = channel.get(source_field)
            if value is not None and not isinstance(value, str):
                raise SyncError(f"ช่อง {channel.get('id')}: ฟิลด์ {source_field} ในทะเบียนช่องต้องเป็นข้อความ")
        kit = {
            "name": channel.get("display_name") or "",
            "handle": channel.get("handle") or "",
            "avatar": kit_avatar_path(channel.get("avatar_asset_path") or "", project_root=project_root, studio_root=studio_root),
            "watermark": channel.get("watermark_text") or "",
            "followTitle": channel.get("follow_title") or "",
        }
        entries.append((channel["id"], channel.get("status") or "", kit))
    return entries


def render_channels_js(entries: list[tuple[str, str, dict]], *, newline: str = "\n") -> str:
    lines = [HEADER.rstrip("\n"), "window.HF_CHANNELS = {"]
    for channel_id, status, kit in entries:
        if status and status != "active":
            lines.append(f"  // status: {status}")
        lines.append(f"  {_js_key(channel_id)}: {{")
        for key in KIT_KEYS:
            lines.append(f"    {key}: {_js_string(kit[key])},")
        lines.append("  },")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    return text.replace("\n", newline) if newline != "\n" else text


def _detect_newline(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def _atomic_write(path: Path, text: str) -> None:
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def sync(
    *,
    registry_path: Path,
    kit_dir: Path,
    project_root: Path,
    apply: bool,
    out=None,
) -> int:
    out = out or sys.stdout
    kit_dir = Path(kit_dir)
    if not kit_dir.is_dir():
        print(f"[sync_channels] ไม่พบโฟลเดอร์ kit: {kit_dir} (ยังไม่ได้ติดตั้ง HyperFrames Studio?) ไม่ได้เขียนไฟล์ใด ๆ", file=out)
        return 2
    target = kit_dir / "channels.js"
    store = ChannelStore(Path(registry_path), project_root=Path(project_root))
    try:
        doc = store.load()
        entries = build_kit_entries(doc["channels"], project_root=Path(project_root), studio_root=kit_dir.parent)
    except (ChannelError, SyncError) as exc:
        message = exc.message if isinstance(exc, ChannelError) else str(exc)
        print(f"[sync_channels] หยุด: {message}", file=out)
        return 2

    for channel in doc["channels"]:
        issues = readiness(channel, channels=doc["channels"], project_root=store.project_root, metrics=store.metrics)
        for issue in issues:
            print(f"[sync_channels] คำเตือน ช่อง {channel['id']}: {issue.message}", file=out)

    # read_bytes: read_text would translate CRLF and break newline detection
    current = target.read_bytes().decode("utf-8") if target.is_file() else ""
    newline = _detect_newline(current) if current else "\n"
    generated = render_channels_js(entries, newline=newline)
    if generated == current:
        print(f"[sync_channels] {target.name} ตรงกับทะเบียนช่องแล้ว (0 การเปลี่ยนแปลง)", file=out)
        return 0

    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        generated.splitlines(keepends=True),
        fromfile=f"{target.name} (ปัจจุบัน)",
        tofile=f"{target.name} (จากทะเบียนช่อง)",
    )
    out.write("".join(diff))
    if not apply:
        print("\n[sync_channels] dry-run: ยังไม่ได้เขียนไฟล์ ใช้ --apply เพื่อบันทึก", file=out)
        return 0

    if target.is_file():
        backup = target.with_name(target.name + ".bak")
        shutil.copy2(target, backup)
        print(f"[sync_channels] สำรองไฟล์เดิมไว้ที่ {backup}", file=out)
    _atomic_write(target, generated)
    if target.read_bytes().decode("utf-8") != generated:  # pragma: no cover - defensive
        print("[sync_channels] เขียนไฟล์แล้วแต่อ่านกลับไม่ตรง กรุณาตรวจสอบ", file=out)
        return 2
    print(f"[sync_channels] บันทึก {target} แล้ว ({len(entries)} ช่อง)", file=out)
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):  # pragma: no cover
        pass
    parser = argparse.ArgumentParser(description="Sync kit/channels.js from _Docs/channels.json")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="print the diff only (default)")
    mode.add_argument("--apply", action="store_true", help="write kit/channels.js (keeps channels.js.bak)")
    parser.add_argument("--registry", type=Path, default=Path(config.CHANNELS_FILE))
    parser.add_argument("--kit-dir", type=Path, default=Path(config.HYPERFRAMES_STUDIO_DIR) / "kit")
    parser.add_argument("--project-root", type=Path, default=Path(config.BASE_DIR))
    args = parser.parse_args(argv)
    return sync(
        registry_path=args.registry,
        kit_dir=args.kit_dir,
        project_root=args.project_root,
        apply=bool(args.apply),
    )


if __name__ == "__main__":
    sys.exit(main())
