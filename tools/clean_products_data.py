def clean_text(text: str) -> str:
    if not text:
        return ""
    result = text
    for old, new in BRAND_REPLACEMENTS:
        result = result.replace(old, new)
    for old, new in MALE_PARTICLE_REPLACEMENTS:
        result = result.replace(old, new)
    # Strip ellipses
    result = re.sub(r'[\.]{2,}|…', ' ', result)
    result = re.sub(r'\s{2,}', ' ', result).strip()
    return result

