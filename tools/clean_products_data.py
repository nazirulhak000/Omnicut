def clean_products_json():
    if not PRODUCTS_FILE.exists():
        print(f"File not found: {PRODUCTS_FILE}")
        return
    import sys
    sys.path.insert(0, str(BASE_DIR))
    from scripts.tts_sanitizer import TTSSanitizer

    data = json.loads(PRODUCTS_FILE.read_text(encoding="utf-8"))
    for prod in data:
        prod["name"] = TTSSanitizer.clean_display_text(prod.get("name", ""))
        cleaned_angles = []
        for angle in prod.get("angles", []):
            cleaned_angles.append(TTSSanitizer.process_angle(angle))
        prod["angles"] = cleaned_angles

    PRODUCTS_FILE.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Successfully cleaned and updated {PRODUCTS_FILE}")

def clean_active_project():
    if not PROJECT_FILE.exists():
        print(f"Active project file not found: {PROJECT_FILE}")
        return
    pdata = json.loads(PROJECT_FILE.read_text(encoding="utf-8"))
    lines = LOGITECH_ANGLES_SCRIPTS["pain_point"]
    pdata["script_data"]["hook"] = lines[0]
    pdata["script_data"]["full_text"] = "\n".join(lines)
    for i, line in enumerate(pdata["script_data"]["lines"]):
        if i < len(lines):
            line["text"] = lines[i]

    # Clean text in existing cues
    for cue in pdata.get("cues", []):
        cue["text"] = clean_text(cue.get("text", ""))

    PROJECT_FILE.write_text(json.dumps(pdata, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Successfully cleaned and updated {PROJECT_FILE}")

if __name__ == "__main__":
    clean_products_json()
    clean_active_project()
